#!/usr/bin/env python3
"""gen_tool_table — the README's tool table, generated from FastMCP's own listing.

The 0.7 README listed about 18 of 29 tools by hand. This renders every
registered tool (registration order, which follows server.py's sections)
with its arguments and the first sentence of its description, and
tests/test_readme.py fails when README.md and the live listing disagree.

    python scripts/gen_tool_table.py            # print the table
    python scripts/gen_tool_table.py --write    # rewrite it inside README.md
"""
from __future__ import annotations

import argparse
import asyncio
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
START = "<!-- tools:start (generated by scripts/gen_tool_table.py; do not edit by hand) -->"
END = "<!-- tools:end -->"


def _first_sentence(text: str) -> str:
    para = " ".join((text or "").strip().split("\n\n")[0].split())
    m = re.match(r"(.+?[.!?])(\s|$)", para)
    return (m.group(1) if m else para).replace("|", "\\|")


def _kind(tool) -> str:
    ann = tool.annotations
    if ann is not None and ann.readOnlyHint:
        return "read"
    if ann is not None and ann.destructiveHint:
        return "destructive"
    return "write"


def _args(tool) -> str:
    props = (tool.parameters or {}).get("properties", {})
    required = set((tool.parameters or {}).get("required", []))
    parts = [name if name in required else f"{name}?" for name in props]
    return ", ".join(parts) if parts else "none"


def render() -> str:
    sys.path.insert(0, str(ROOT))
    from meshbook_mcp import server

    tools = asyncio.run(server.mcp.list_tools())
    lines = [
        f"{len(tools)} tools. `?` marks an optional argument.",
        "",
        "| Tool | Arguments | Kind | Does |",
        "| --- | --- | --- | --- |",
    ]
    for t in tools:
        lines.append(f"| `{t.name}` | {_args(t)} | {_kind(t)} | {_first_sentence(t.description)} |")
    return "\n".join(lines)


def splice(readme: str, table: str) -> str:
    if START not in readme or END not in readme:
        raise SystemExit("gen_tool_table: README.md has no tools:start/tools:end markers")
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{table}\n{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="gen_tool_table")
    ap.add_argument("--write", action="store_true", help="rewrite the table inside README.md")
    args = ap.parse_args(argv)
    table = render()
    if not args.write:
        print(table)
        return 0
    text = README.read_text(encoding="utf-8")
    README.write_text(splice(text, table), encoding="utf-8", newline="\n")
    print(f"gen_tool_table: README.md updated ({table.count(chr(10)) - 3} tools)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
